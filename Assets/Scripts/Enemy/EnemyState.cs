public enum EnemyState
{
    Idle,         // Стоит, оглядывается
    Patrol,       // Патрулирует маршрут
    Alerted,      // Повышенная готовность (слышит/видит что-то)
    Investigate,  // Подходит к источнику звука или подозрительной точке
    Chase,        // Преследует игрока
    Attack,       // Атакует из укрытия
    Search,       // Ищет игрока, потерявшегося из виду
    Retreat,      // Отступает (ранен, зовёт подкрепление)
    Dead          // Мёртв
}